/**
 * Writes a circuit's game layout (`01_packages/shared/src/track/layouts/<id>.ts`) from its profile
 * and its adaptation in circuits.ts, plus a preview seen from above (`preview/<id>.png`,
 * git-ignored) to compare with the owner's reference PNG.
 * Usage: node --import ./01_tools/openf1/resolveTs.ts 01_tools/openf1/layout.ts <id>
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { circuitById, widthFactorOf } from './circuits.ts';
import { generate } from './generate.ts';
import { layoutPath, profilePath, readJson, type CircuitProfile } from './openf1.ts';
import { Canvas, type Rgb } from './png.ts';

const circuit = circuitById(process.argv[2] ?? '');
const profile = readJson<CircuitProfile>(profilePath(circuit.id));
const { definition, stations, adapted } = generate(profile, circuit, circuit.scale);

const time = (s: number): string =>
  s >= 60 ? `${Math.floor(s / 60)}:${(s % 60).toFixed(3).padStart(6, '0')}` : s.toFixed(3);
const pole = profile.pole;
const source = profile.source;
const lines = [
  `// Generated by 01_tools/openf1/layout.ts — do not edit by hand: change 01_tools/openf1/circuits.ts`,
  `// and re-run the tool (see 01_docs/circuits.md).`,
  `import { vec2 } from '../../math/vec2';`,
  `import type { TrackDefinition, TrackPoint } from '../types';`,
  ``,
  `const p = (x: number, z: number, width: number): TrackPoint => ({ at: vec2(x, z), width });`,
  ``,
  `/**`,
  ` * ${circuit.name}: the real circuit from open data, adapted to the game.`,
  ` * - Shape: road centreline from OpenStreetMap (© OpenStreetMap contributors, ODbL), relation`,
  ` *   ${circuit.osmRelation}, ordered and placed by the OpenF1 pole lap (https://openf1.org).`,
  ` * - Target: the 2025 pole, ${time(pole.time)} (car #${source.driver}, lap ${source.lap}, OpenF1 session ${source.session}),`,
  ` *   sectors ${pole.sectors.map(time).join(' / ')}; the sectors start where they really do.`,
  ` * - Scale ${circuit.scale} (real ${Math.round(profile.length)} m), calibrated so the Hard bot laps in the pole time.`,
  ` * - Widths: the real ones (${circuit.widthRange.join('–')} m) × ${widthFactorOf(circuit)}.`,
  ` * - Normal kerbs only (no high kerbs), wider than on the imaginary tracks.`,
  ` */`,
  `export const ${circuit.constName}: TrackDefinition = {`,
  `  name: '${definition.name}',`,
  `  minWidth: ${definition.minWidth},`,
  `  runoffWidth: ${definition.runoffWidth},`,
  ...(definition.kerbs ? [`  kerbs: '${definition.kerbs}',`] : []),
  `  kerbBand: { inset: ${definition.kerbBand!.inset}, outset: ${definition.kerbBand!.outset} },`,
  `  sectorPoints: [${definition.sectorPoints!.join(', ')}],`,
  `  highKerbs: [],`,
  `  points: [`,
  ...definition.points.map((p) => `    p(${p.at.x}, ${p.at.z}, ${p.width}),`),
  `  ],`,
  `};`,
  ``,
];
writeFileSync(layoutPath(circuit.id), lines.join('\n'));

// Preview seen from above: x to the right, -z up (as the game's chase camera sees the map).
const xs = stations.map((p) => p[0]);
const zs = stations.map((p) => p[1]);
const size = 900;
const pad = 40;
const span = Math.max(Math.max(...xs) - Math.min(...xs), Math.max(...zs) - Math.min(...zs));
const k = (size - 2 * pad) / span;
const toPx = (x: number, z: number): [number, number] => [
  pad + (x - Math.min(...xs)) * k,
  pad + (z - Math.min(...zs)) * k,
];
const canvas = new Canvas(size, size, [255, 255, 255]);
/** Half-width at station `i`: that of the control point it belongs to. */
const half = (i: number): number => {
  const { points } = definition;
  return (
    points[Math.min(points.length - 1, Math.floor((i / stations.length) * points.length))]!.width /
    2
  );
};
stations.forEach((a, i) => {
  const b = stations[(i + 1) % stations.length]!;
  const len = Math.hypot(b[0] - a[0], b[1] - a[1]);
  const nx = -(b[1] - a[1]) / len;
  const nz = (b[0] - a[0]) / len;
  for (const side of [-1, 1]) {
    const [x0, y0] = toPx(a[0] + nx * side * half(i), a[1] + nz * side * half(i));
    const [x1, y1] = toPx(b[0] + nx * side * half(i), b[1] + nz * side * half(i));
    canvas.line(x0, y0, x1, y1, [24, 24, 32], 1);
  }
});
const mark = (point: number, color: Rgb): void => {
  const { at } = definition.points[point]!;
  canvas.dot(...toPx(at.x, at.z), color, 5);
};
mark(0, [220, 30, 30]);
for (const s of definition.sectorPoints!) mark(s, [240, 190, 0]);
mark(3, [30, 120, 220]); // just after the line: shows the driving direction
const preview = join(dirname(fileURLToPath(import.meta.url)), 'preview');
mkdirSync(preview, { recursive: true });
canvas.save(join(preview, `${circuit.id}.png`));

console.log(
  `${circuit.name}: ${definition.points.length} control points, width ${definition.minWidth}–` +
    `${Math.max(...definition.points.map((p) => p.width))} m, sectors at points ` +
    `${definition.sectorPoints!.join(' / ')}; ${adapted.moved} stations moved for the game's limits ` +
    `(rounds: radius ${adapted.radiusRounds}, separation ${adapted.separationRounds}, folds ${adapted.foldRounds})`,
);
